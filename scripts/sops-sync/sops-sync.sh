# shellcheck shell=bash
# Generates .sops.yaml from keys/admins, keys/hosts/<host>.age and each host's
# `host.role`, then re-encrypts the secrets files to exactly those recipients
# (YubiKey). Deterministic: the result depends only on the repo, so running it
# again changes nothing, and a removed key file removes that host's access.
#
#   workstation hosts: hosts/_shared/** and home/** secrets
#   server hosts:      only hosts/<host>/secrets.yaml
#
# usage: sops-sync [--no-reencrypt] [--verify HOST KEYFILE]

reencrypt=yes
verify_host=""
verify_key=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --no-reencrypt)
      reencrypt=no
      shift
      ;;
    --verify)
      verify_host="$2"
      verify_key="$3"
      shift 3
      ;;
    *)
      echo "usage: sops-sync [--no-reencrypt] [--verify HOST KEYFILE]" >&2
      exit 1
      ;;
  esac
done

cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)" || exit 1
[[ -f flake.nix && -d keys/hosts ]] || {
  echo "run inside the nix-config repo" >&2
  exit 1
}

roles=$(nix eval --json .#nixosConfigurations --apply \
  'cs: builtins.mapAttrs (n: c: c.config.host.role or "workstation") cs')

mapfile -t admin_pgp < <(awk '$1 == "pgp" { print $2 }' keys/admins)
mapfile -t admin_age < <(awk '$1 == "age" { print $2 }' keys/admins)
workstations=()
servers=()
for f in keys/hosts/*.age; do
  [[ -e $f ]] || continue
  host=$(basename "$f" .age)
  key=$(tr -d '[:space:]' <"$f")
  [[ $key =~ ^age1[a-z0-9]{58}$ ]] || {
    echo "$f: not an age public key" >&2
    exit 1
  }
  role=$(jq -r --arg h "$host" '.[$h] // "unknown"' <<<"$roles")
  case $role in
    workstation) workstations+=("$host") ;;
    server) servers+=("$host") ;;
    *)
      echo "$f: no nixosConfigurations.$host in flake.nix" >&2
      exit 1
      ;;
  esac
done

# key_groups entry: all admins plus the given hosts
recipients() {
  echo "      - pgp:"
  for k in "${admin_pgp[@]}"; do echo "          - $k"; done
  echo "        age:"
  for k in "${admin_age[@]}"; do echo "          - $k"; done
  for h in "$@"; do echo "          - $(tr -d '[:space:]' <"keys/hosts/$h.age") # $h"; done
}

{
  echo "# GENERATED by sops-sync from keys/admins, keys/hosts/*.age and each"
  echo "# host's host.role. Do not edit; see docs/secrets.md."
  echo "creation_rules:"
  for s in "${servers[@]}"; do
    echo "  - path_regex: hosts/$s/secrets\\.yaml\$"
    echo "    key_groups:"
    recipients "$s"
  done
  echo "  - path_regex: (hosts/_shared|home)/.*secrets\\.yaml\$"
  echo "    key_groups:"
  recipients "${workstations[@]}"
} >.sops.yaml
echo "wrote .sops.yaml: workstations: ${workstations[*]:-none}; servers: ${servers[*]:-none}"

[[ $reencrypt == yes ]] || exit 0

# Make the YubiKey PIN prompt appear in this terminal (not some other one).
if tty -s; then
  GPG_TTY=$(tty)
  export GPG_TTY
  gpg-connect-agent updatestartuptty /bye >/dev/null || true
fi

failed=0
while IFS= read -r f; do
  # sops doesn't rewrite a file whose recipients already match
  if out=$(sops updatekeys -y "$f" 2>&1); then
    grep -q "already up to date" <<<"$out" || echo "re-encrypted $f"
  else
    echo "$out" >&2
    failed=1
  fi
done < <(find hosts home -name '*secrets.yaml' | sort)

if [[ -n $verify_host ]]; then
  role=$(jq -r --arg h "$verify_host" '.[$h]' <<<"$roles")
  [[ $role != null ]] || {
    echo "unknown host: $verify_host (no keys/hosts/$verify_host.age or host config)" >&2
    exit 1
  }
  if [[ $role == server ]]; then
    mapfile -t files < <(find "hosts/$verify_host" -name '*secrets.yaml' | sort)
  else
    mapfile -t files < <(find hosts/_shared home -name '*secrets.yaml' | sort)
  fi
  for f in "${files[@]}"; do
    # only the host's key: no gpg, not ~/.config/sops/age/keys.txt either
    env -u SOPS_AGE_KEY HOME=/nonexistent XDG_CONFIG_HOME=/nonexistent GNUPGHOME=/nonexistent \
      SOPS_AGE_KEY_FILE="$verify_key" sops decrypt "$f" >/dev/null ||
      {
        echo "$verify_host can NOT decrypt $f" >&2
        failed=1
      }
  done
  [[ $failed -eq 0 ]] && echo "OK: $verify_host can decrypt its ${#files[@]} secrets file(s)"
fi

if [[ $failed -ne 0 ]]; then
  echo "FAILED. If gpg said 'Invalid ID' the PIN prompt timed out, see docs/secrets.md" >&2
  exit 1
fi
echo "Done. Commit keys/hosts, .sops.yaml and the secrets files."
